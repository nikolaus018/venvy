#!/usr/bin/env python3
"""
Build a single copy-paste command that installs or updates Venvy on a Debian
server — with main.py, index.html and vendor/ embedded in it. No download
server needed: paste the line into an SSH session and it does the rest.

Usage:
    python3 dist.py                      # same setup as the old setup.sh
    python3 dist.py --host 127.0.0.1     # only reachable via the tunnel
    python3 dist.py --app-users          # run as root with per-app users
    python3 dist.py --env TRUSTED_PROXY_IPS=10.0.0.5 --env VENVY_LOG_MAX_MB=50

It writes dist/venvy-install.txt and, on macOS, copies it to the clipboard.

On the server the command:
  * installs missing apt packages (python3-venv, cargo, …) — skips apt entirely
    when everything is already there
  * builds a Python runtime venv in /opt/venvy/.runtime for Venvy itself
  * verifies every embedded file against its SHA-256 before touching anything
  * stops Venvy, backs up data.db, keeps the previous main.py/index.html/vendor
    in /opt/venvy/.previous, swaps the new files in, restarts, and waits for
    /api/health — rolling back to the previous files automatically if the new
    version doesn't come up
Data (data.db, apps/, backups/, .venvy_key) is never touched beyond the backup.

The whole script body is one bash function that's only called on its last
line, so a paste that got cut off is a syntax error and runs nothing at all.
"""

import argparse
import base64
import datetime
import gzip
import hashlib
import re
import secrets
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).parent.resolve()
FILES = ["main.py", "index.html"]
VENDOR_DIR = "vendor"
APT_PACKAGES = [
    "curl", "sqlite3", "build-essential", "cargo", "rustc",
    "python3", "python3-venv", "python3-pip", "ca-certificates",
]
# What main.py needs to run (see _REQUIRED at its top) plus psutil for metrics.
# uvicorn[standard], not plain uvicorn: the plain package has no WebSocket
# library, so the terminal can't connect.
PY_PACKAGES = [
    "fastapi", "uvicorn[standard]", "sqlmodel", "aiofiles", "aiohttp",
    "cryptography", "python-multipart", "psutil",
]


def collect_files() -> list:
    """[(relative_path, bytes)] for everything that ships."""
    out = []
    for name in FILES:
        out.append((name, (ROOT / name).read_bytes()))
    vendor = ROOT / VENDOR_DIR
    if vendor.is_dir():
        for f in sorted(vendor.iterdir()):
            if f.is_file() and not f.name.startswith("."):
                out.append((f"{VENDOR_DIR}/{f.name}", f.read_bytes()))
    return out


def version_label() -> str:
    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    try:
        rev = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                             capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain", "--", *FILES, VENDOR_DIR], cwd=ROOT,
                               capture_output=True, text=True).stdout.strip()
        return f"{rev}{'+uncommitted' if dirty else ''} ({stamp})"
    except Exception:
        return stamp


def embed(rel: str, data: bytes, delim: str) -> tuple:
    """Return (bash that writes the file into $STAGE, sha256 of what it writes)."""
    text = data.decode("utf-8")  # all shipped files are text
    if "\r" in text:
        raise SystemExit(f"{rel} contains CR characters; normalise line endings first.")
    # A heredoc always ends its output with a newline.
    written = text if text.endswith("\n") else text + "\n"
    digest = hashlib.sha256(written.encode("utf-8")).hexdigest()
    parent = str(Path(rel).parent)
    mk = f'mkdir -p "$STAGE/{parent}"\n' if parent != "." else ""
    return (f"{mk}cat > \"$STAGE/{rel}\" <<'{delim}'\n{written}{delim}\n", digest)


def build_script(files, args, version: str) -> str:
    blob = "".join(content.decode("utf-8") for _, content in files)
    while True:
        delim = f"__VENVY_FILE_END_{secrets.token_hex(8)}__"
        if delim not in blob:
            break

    writers, checks = [], []
    for rel, data in files:
        w, digest = embed(rel, data, delim)
        writers.append(w)
        checks.append(f"{digest}  {rel}")

    env_lines = "".join(f"Environment={shlex.quote(e)}\n" for e in args.env)
    if args.app_users:
        env_lines += "Environment=VENVY_APP_USERS=1\n"
    service_user = "root" if args.app_users else "$ACTUAL_USER"
    service_group = "root" if args.app_users else "$ACTUAL_GROUP"

    q = shlex.quote
    return f"""#!/usr/bin/env bash
# Venvy installer/updater — generated by dist.py, version {version}
venvy_install() {{
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive

DEST_DIR={q(args.dest)}
PORT={args.port}
HOST={q(args.host)}
VERSION={q(version)}

echo "==========================================================="
echo "   Venvy installer — $VERSION"
echo "==========================================================="

if [ "$EUID" -ne 0 ]; then
  if ! command -v sudo >/dev/null 2>&1; then
    echo "[!] Not root and 'sudo' is not installed. Run as root or install sudo."
    exit 1
  fi
  SUDO="sudo"
else
  SUDO=""
fi
ACTUAL_USER="${{SUDO_USER:-$(whoami)}}"
ACTUAL_GROUP="$(id -gn "$ACTUAL_USER")"

# ── 1. Unpack and verify the embedded files (nothing is touched yet) ─────────
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
{"".join(writers)}
echo "[*] Verifying embedded files..."
( cd "$STAGE" && sha256sum --quiet -c - ) <<'__VENVY_SUMS__' || {{ echo "[!] Embedded files are corrupted (bad copy/paste?). Nothing was changed."; exit 1; }}
{chr(10).join(checks)}
__VENVY_SUMS__

# ── 2. System packages (apt only runs if something is missing) ──────────────
MISSING=""
for p in {" ".join(APT_PACKAGES)}; do
  dpkg -s "$p" >/dev/null 2>&1 || MISSING="$MISSING $p"
done
if [ -n "$MISSING" ]; then
  echo "[*] Installing system packages:$MISSING"
  $SUDO apt-get update -y
  $SUDO apt-get install -y --no-install-recommends $MISSING
else
  echo "[*] System packages already installed."
fi

# ── 3. Python runtime for Venvy itself ──────────────────────────────────────
$SUDO mkdir -p "$DEST_DIR"
RUNTIME="$DEST_DIR/.runtime"
if [ ! -x "$RUNTIME/bin/python" ] || ! "$RUNTIME/bin/python" -c "import sys" >/dev/null 2>&1; then
  echo "[*] Creating Python runtime in $RUNTIME..."
  $SUDO rm -rf "$RUNTIME"
  $SUDO python3 -m venv "$RUNTIME"
fi
echo "[*] Ensuring Python packages..."
$SUDO "$RUNTIME/bin/pip" install -q --disable-pip-version-check {" ".join(shlex.quote(p) for p in PY_PACKAGES)}

# ── 4. Stop, back up, swap files in ─────────────────────────────────────────
if systemctl list-unit-files venvy.service >/dev/null 2>&1 && [ -f /etc/systemd/system/venvy.service ]; then
  echo "[*] Stopping Venvy..."
  $SUDO systemctl stop venvy.service || true
fi

if [ -f "$DEST_DIR/data.db" ]; then
  BACKUP_NAME="data.db.bak.$(date +%Y%m%d_%H%M%S)"
  echo "[*] Backing up database -> $BACKUP_NAME"
  $SUDO sqlite3 "$DEST_DIR/data.db" ".backup '$DEST_DIR/$BACKUP_NAME'"
  $SUDO chmod 600 "$DEST_DIR/$BACKUP_NAME"
  # keep the 5 newest
  ls -1t "$DEST_DIR"/data.db.bak.* 2>/dev/null | tail -n +6 | while read -r old; do $SUDO rm -f "$old"; done || true
fi

echo "[*] Installing new files..."
$SUDO rm -rf "$DEST_DIR/.previous"
$SUDO mkdir -p "$DEST_DIR/.previous"
for f in main.py index.html vendor; do
  if [ -e "$DEST_DIR/$f" ]; then $SUDO cp -a "$DEST_DIR/$f" "$DEST_DIR/.previous/"; fi
done
$SUDO rm -rf "$DEST_DIR/vendor"
$SUDO cp -a "$STAGE/." "$DEST_DIR/"
echo "$VERSION" | $SUDO tee "$DEST_DIR/VERSION" >/dev/null

if [ "{service_user}" != "root" ]; then
  $SUDO chown -R "$ACTUAL_USER:$ACTUAL_GROUP" "$DEST_DIR"
fi

# ── 5. systemd service ──────────────────────────────────────────────────────
cat <<EOF | $SUDO tee /etc/systemd/system/venvy.service > /dev/null
[Unit]
Description=Venvy Backend Service
After=network.target

[Service]
Type=simple
User={service_user}
Group={service_group}
WorkingDirectory=$DEST_DIR
ExecStart=$RUNTIME/bin/python $DEST_DIR/main.py --host $HOST --port $PORT
Restart=always
RestartSec=5
Environment=PYTHONUNBUFFERED=1
{env_lines}
[Install]
WantedBy=multi-user.target
EOF

$SUDO systemctl daemon-reload
$SUDO systemctl enable venvy.service >/dev/null 2>&1
$SUDO systemctl restart venvy.service

# ── 6. Health check, automatic rollback ─────────────────────────────────────
echo "[*] Waiting for Venvy to come up..."
for i in $(seq 1 45); do
  if curl -fsS "http://127.0.0.1:$PORT/api/health" >/dev/null 2>&1; then
    SYSTEM_IP=$(hostname -I 2>/dev/null | awk '{{print $1}}')
    [ -z "$SYSTEM_IP" ] && SYSTEM_IP="localhost"
    echo "==========================================================="
    echo "[+] Venvy $VERSION is running."
    echo "    Web UI:  http://$SYSTEM_IP:$PORT"
    echo "    Status:  sudo systemctl status venvy"
    echo "    Logs:    sudo journalctl -u venvy -f"
    echo "==========================================================="
    return 0
  fi
  sleep 1
done

echo "[!] Venvy did not become healthy. Last log lines:"
$SUDO journalctl -u venvy.service -n 30 --no-pager || true
if [ -f "$DEST_DIR/.previous/main.py" ]; then
  echo "[!] Rolling back to the previous version..."
  $SUDO rm -rf "$DEST_DIR/vendor"
  $SUDO cp -a "$DEST_DIR/.previous/." "$DEST_DIR/"
  $SUDO systemctl restart venvy.service
  echo "[!] Previous version restored. The failed files were not kept."
fi
exit 1
}}
venvy_install "$@"
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--host", default="0.0.0.0", help="address Venvy binds to (default 0.0.0.0, as before)")
    ap.add_argument("--port", type=int, default=54783)
    ap.add_argument("--dest", default="/opt/venvy", help="install directory (default /opt/venvy)")
    ap.add_argument("--app-users", action="store_true",
                    help="run Venvy as root with VENVY_APP_USERS=1 (per-app Unix users)")
    ap.add_argument("--env", action="append", default=[], metavar="KEY=VALUE",
                    help="extra environment variable for the service (repeatable)")
    ap.add_argument("--out", default=str(ROOT / "dist" / "venvy-install.txt"))
    ap.add_argument("--script", action="store_true", help="also write the plain install script next to it")
    args = ap.parse_args()

    for e in args.env:
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*=[^\n]*", e):
            raise SystemExit(f"--env must look like KEY=VALUE, got {e!r}")

    files = collect_files()
    version = version_label()
    script = build_script(files, args, version)

    payload = base64.b64encode(gzip.compress(script.encode("utf-8"), compresslevel=9, mtime=0)).decode("ascii")
    oneliner = f"echo '{payload}' | base64 -d | gunzip | bash\n"

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(oneliner)
    if args.script:
        out.with_suffix(".sh").write_text(script)

    copied = False
    if shutil.which("pbcopy"):
        subprocess.run(["pbcopy"], input=oneliner.encode(), check=False)
        copied = True

    print(f"Venvy {version}")
    for rel, data in files:
        print(f"  {rel:32} {len(data):>9,} bytes")
    print(f"One-liner: {len(oneliner):,} characters -> {out}")
    print("Copied to clipboard — paste it into an SSH session on the server." if copied
          else "Paste the contents of that file into an SSH session on the server.")


if __name__ == "__main__":
    main()
