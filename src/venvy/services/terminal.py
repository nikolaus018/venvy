"""Interactive shell sessions, jailed to an app's directory.

A terminal is a real PTY running bash, forked with the app's virtualenv already
activated and its working directory pinned to the app directory. The jail is
enforced inside the shell by an overridden ``cd`` plus a ``PROMPT_COMMAND``
guard that pulls the shell back if the working directory ever drifts out.

That jail is a **usability guardrail, not a security boundary.** The shell runs
as the same OS user as Venvy, so anyone with operator access can reach the rest
of the host through any program the shell can launch. Real isolation needs a
container or a separate unprivileged user — see docs/security.md.

The PTY machinery is POSIX-only. The imports are guarded so that importing
Venvy on Windows or in a test environment succeeds; only opening a terminal
fails, and it fails with a clear message.
"""

from __future__ import annotations

import asyncio
import codecs
import json
import logging
import os
import re
import shutil
import signal
from pathlib import Path

from fastapi import WebSocket
from sqlmodel import Session

from venvy.core.crypto import decrypt_secret
from venvy.db.models import App

__all__ = ["PTY_AVAILABLE", "TerminalManager", "terminal_manager"]

logger = logging.getLogger(__name__)

try:  # pragma: no cover - POSIX only
    import fcntl
    import pty
    import struct
    import termios

    PTY_AVAILABLE = True
except ImportError:  # pragma: no cover - Windows / restricted environments
    fcntl = pty = struct = termios = None  # type: ignore[assignment]
    PTY_AVAILABLE = False

#: WebSocket close code for a policy violation (RFC 6455).
_WS_POLICY_VIOLATION = 1008

#: Initial terminal geometry, replaced by the client's first resize message.
_DEFAULT_ROWS, _DEFAULT_COLS = 50, 220

#: A client message beginning with this byte is a control frame (a resize),
#: not keystrokes to forward to the shell.
_CONTROL_PREFIX = "\x00"
#: Cap on a control frame, so a malformed one cannot force a huge JSON parse.
_MAX_CONTROL_BYTES = 4096

_PTY_READ_SIZE = 4096
_WS_SEND_TIMEOUT = 30.0
_WS_RECEIVE_TIMEOUT = 5.0
#: How long the shell gets to exit after SIGHUP before it is killed.
_REAP_ATTEMPTS = 30
_REAP_INTERVAL = 0.1

_BASHRC_NAME = ".bashrc-venvy"


def _render_bashrc(jail_root: Path, venv_bin: Path, prompt_name: str) -> str:
    """Build the shell init script that activates the venv and enforces the jail."""
    activate = venv_bin / "activate"
    return f"""#!/bin/bash
# Generated by Venvy — do not edit; this file is rewritten on every session.

if [ -f "{activate}" ]; then source "{activate}"; fi

# ── Directory jail ───────────────────────────────────────────────────────────
export JAIL_DIR="{jail_root}"

# Replace `cd` so it refuses to leave the app directory.
function cd() {{
    local target jail_resolved
    jail_resolved="$(realpath -m "$JAIL_DIR" 2>/dev/null || echo "$JAIL_DIR")"
    if [ -z "$1" ]; then
        target="$jail_resolved"
    elif [[ "$1" == /* ]]; then
        target="$(realpath -m "$1" 2>/dev/null || echo "$1")"
    else
        target="$(realpath -m "$(builtin pwd)/$1" 2>/dev/null || echo "$(builtin pwd)/$1")"
    fi
    if [[ "$target" != "$jail_resolved" && "$target" != "$jail_resolved/"* ]]; then
        echo -e "\\e[31m✗ Access denied: cannot navigate outside the app directory.\\e[0m"
        return 1
    fi
    builtin cd "$target"
}}

# Catch drift from anything that changes directory without going through `cd`.
function _venvy_jail_guard() {{
    local cwd jail_resolved
    cwd="$(builtin pwd -P 2>/dev/null)"
    jail_resolved="$(realpath -m "$JAIL_DIR" 2>/dev/null || echo "$JAIL_DIR")"
    if [[ "$cwd" != "$jail_resolved" && "$cwd" != "$jail_resolved/"* ]]; then
        builtin cd "$JAIL_DIR"
        echo -e "\\e[33m⚠ Returned to app directory (outside access blocked).\\e[0m"
    fi
}}
PROMPT_COMMAND="_venvy_jail_guard"
# ─────────────────────────────────────────────────────────────────────────────

export PS1='\\[\\e[0;32m\\]{prompt_name}\\[\\e[0m\\] \\[\\e[1;34m\\]\\w\\[\\e[0m\\]\\$ '
alias ls='ls --color=auto'
alias ll='ls -la'
"""


def _write_bashrc(jail_root: Path, venv_bin: Path, prompt_name: str) -> Path:
    """Write the session's bashrc into the app directory and return its path."""
    path = jail_root / _BASHRC_NAME
    path.write_text(_render_bashrc(jail_root, venv_bin, prompt_name), encoding="utf-8")
    path.chmod(0o644)
    return path


def _safe_prompt_name(name: str) -> str:
    """Reduce an app name to something safe to embed in a shell prompt."""
    cleaned = re.sub(r"[^A-Za-z0-9_.+\-]", "-", name)[:24].strip("-")
    return cleaned or "app"


def _build_shell_env(app: App, venv_bin: Path) -> dict[str, str]:
    """Build a minimal environment for the shell, plus the app's own variables."""
    env = {
        "TERM": "xterm-256color",
        "LANG": os.environ.get("LANG", "en_US.UTF-8"),
        # Falls back to /tmp only when the service account has no HOME;
        # bash needs somewhere writable or the shell fails to start.
        "HOME": os.environ.get("HOME", "/tmp"),  # noqa: S108
        "USER": os.environ.get("USER", ""),
        "LOGNAME": os.environ.get("LOGNAME", ""),
        "SHELL": shutil.which("bash") or "/bin/bash",
        "PATH": f"{venv_bin}:/usr/local/bin:/usr/bin:/bin",
        "VIRTUAL_ENV": app.venv_path,
        "PYTHONUNBUFFERED": "1",
    }
    env = {key: value for key, value in env.items() if value}

    try:
        extra = json.loads(decrypt_secret(app.env_json) or "{}")
        if isinstance(extra, dict):
            env.update({str(k): str(v) for k, v in extra.items()})
    except (ValueError, TypeError):
        logger.warning("App %s has unparseable env_json; the terminal ignores it.", app.id)
    return env


def _loopback_socket_fds() -> set[int]:
    """Return this process's file descriptors that are loopback sockets.

    Called in the forked child before closing inherited descriptors. Uvicorn's
    listening socket must survive the ``closerange`` sweep: closing it in a
    child that then execs would tear down the server's own listener.
    """
    keep: set[int] = set()
    inodes: set[int] = set()
    for tcp_file in ("/proc/net/tcp", "/proc/net/tcp6"):
        try:
            with open(tcp_file) as handle:
                for line in handle:
                    parts = line.split()
                    if len(parts) < 10:
                        continue
                    hex_ip = parts[1].split(":")[0]
                    if hex_ip in (
                        "7F000001",
                        "0100007F",
                        "00000001",
                        "00000000000000000000000001000000",
                    ):
                        try:
                            inodes.add(int(parts[9]))
                        except ValueError:
                            continue
        except OSError:
            continue

    if not inodes:
        return keep

    fd_dir = f"/proc/{os.getpid()}/fd"
    try:
        # os.listdir rather than Path.iterdir: this runs between fork and exec,
        # where allocating as little as possible is the safe choice.
        entries = os.listdir(fd_dir)  # noqa: PTH208
    except OSError:
        return keep

    for entry in entries:
        try:
            fd = int(entry)
            if fd < 3:
                continue
            link = os.readlink(f"{fd_dir}/{entry}")  # noqa: PTH115  (see above)
            if link.startswith("socket:[") and int(link[8:-1]) in inodes:
                keep.add(fd)
        except (ValueError, OSError):
            continue
    return keep


def _close_inherited_fds(keep: set[int]) -> None:
    """Close every descriptor above stderr except those in *keep*."""
    try:
        max_fd = os.sysconf("SC_OPEN_MAX")
    except (ValueError, OSError):
        max_fd = 4096

    if not keep:
        os.closerange(3, max_fd)
        return

    cursor = 3
    for fd in sorted(keep):
        if fd > cursor:
            os.closerange(cursor, fd)
        cursor = fd + 1
    if cursor < max_fd:
        os.closerange(cursor, max_fd)


class TerminalManager:
    """Bridges a WebSocket to a PTY-backed bash session inside an app directory."""

    async def start_terminal(
        self,
        websocket: WebSocket,
        app_id: int,
        session: Session,
        user_id: int,
        user_role: str,
    ) -> None:
        """Attach *websocket* to a new shell for *app_id*.

        Returns once either side closes; the shell and its PTY are always torn
        down before returning.
        """
        if not PTY_AVAILABLE:
            await websocket.close(
                code=_WS_POLICY_VIOLATION,
                reason="Terminals require a POSIX host with PTY support.",
            )
            return

        if user_role not in ("admin", "operator"):
            await websocket.close(
                code=_WS_POLICY_VIOLATION,
                reason="Operator or admin privileges required for terminal access.",
            )
            return

        app = session.get(App, app_id)
        if not app:
            await websocket.close(code=_WS_POLICY_VIOLATION, reason="App not found.")
            return

        venv_bin = Path(app.venv_path) / "bin"

        def _prepare() -> tuple[Path, Path]:
            """Resolve the jail root and write the session's bashrc."""
            root = Path(app.app_dir).resolve()
            return root, _write_bashrc(root, venv_bin, _safe_prompt_name(app.name))

        try:
            # Both steps touch the filesystem, so they go through a thread
            # rather than blocking the event loop on every terminal open.
            jail_root, bashrc = await asyncio.to_thread(_prepare)
        except OSError as exc:
            logger.error("Could not write the terminal bashrc for app %s: %s", app_id, exc)
            await websocket.close(code=_WS_POLICY_VIOLATION, reason="Could not prepare the shell.")
            return

        env = _build_shell_env(app, venv_bin)
        logger.info("Terminal opened for app '%s' by user %s", app.name, user_id)
        await self._run_pty_session(websocket, jail_root, bashrc, env)

    async def _run_pty_session(
        self,
        websocket: WebSocket,
        jail_root: Path,
        bashrc: Path,
        env: dict[str, str],
    ) -> None:
        """Fork the shell and pump bytes between it and the WebSocket."""
        master_fd = slave_fd = -1
        child_pid = -1

        try:
            master_fd, slave_fd = pty.openpty()
            self._set_winsize(master_fd, _DEFAULT_ROWS, _DEFAULT_COLS)

            child_pid = os.fork()
            if child_pid == 0:
                self._exec_shell_in_child(slave_fd, jail_root, bashrc, env)
                # _exec_shell_in_child never returns; this is belt and braces.
                os._exit(1)

            os.close(slave_fd)
            slave_fd = -1

            await self._pump(websocket, master_fd)

        except Exception:
            logger.exception("PTY session failed")
        finally:
            await self._teardown(websocket, child_pid, master_fd, slave_fd)

    @staticmethod
    def _set_winsize(fd: int, rows: int, cols: int) -> None:
        """Set the terminal window size on *fd*, ignoring failures."""
        try:
            fcntl.ioctl(fd, termios.TIOCSWINSZ, struct.pack("HHHH", rows, cols, 0, 0))
        except OSError:
            pass

    @staticmethod
    def _exec_shell_in_child(
        slave_fd: int, jail_root: Path, bashrc: Path, env: dict[str, str]
    ) -> None:
        """Set up the forked child and exec bash. Never returns.

        Runs between ``fork`` and ``exec``, so it must not allocate through the
        parent's async machinery or touch the event loop.
        """
        try:
            # The parent (uvicorn) ignores or handles these; the shell must not
            # inherit that, or Ctrl-C would do nothing.
            for sig in (signal.SIGINT, signal.SIGTERM, signal.SIGPIPE):
                signal.signal(sig, signal.SIG_DFL)

            os.setsid()
            fcntl.ioctl(slave_fd, termios.TIOCSCTTY, 0)
            os.dup2(slave_fd, 0)
            os.dup2(slave_fd, 1)
            os.dup2(slave_fd, 2)

            _close_inherited_fds(_loopback_socket_fds())

            os.chdir(str(jail_root))
            shell = env.get("SHELL", "/bin/bash")
            os.execvpe(shell, [shell, "--rcfile", str(bashrc)], env)
        except Exception:
            # Cannot log usefully here — stderr is the PTY the user is watching,
            # and the logging machinery may not be fork-safe.
            pass
        os._exit(1)

    async def _pump(self, websocket: WebSocket, master_fd: int) -> None:
        """Run the reader and writer until either finishes."""
        loop = asyncio.get_running_loop()
        stop = asyncio.Event()

        async def reader() -> None:
            """PTY → WebSocket."""
            # Incremental so a multi-byte character split across two reads is
            # not mangled into replacement characters.
            decoder = codecs.getincrementaldecoder("utf-8")(errors="replace")
            try:
                while not stop.is_set():
                    try:
                        data = await loop.run_in_executor(None, os.read, master_fd, _PTY_READ_SIZE)
                    except OSError:
                        break
                    if not data:
                        break
                    text = decoder.decode(data)
                    if not text:
                        continue
                    try:
                        await asyncio.wait_for(websocket.send_text(text), timeout=_WS_SEND_TIMEOUT)
                    except (TimeoutError, Exception):
                        break
            finally:
                stop.set()

        async def writer() -> None:
            """WebSocket → PTY."""
            try:
                while not stop.is_set():
                    try:
                        data = await asyncio.wait_for(
                            websocket.receive_text(), timeout=_WS_RECEIVE_TIMEOUT
                        )
                    except TimeoutError:
                        continue  # poll again so `stop` is observed promptly
                    except Exception:
                        break
                    if not data:
                        continue
                    if data.startswith(_CONTROL_PREFIX):
                        self._handle_control_frame(data[1:], master_fd)
                        continue
                    try:
                        await loop.run_in_executor(None, os.write, master_fd, data.encode("utf-8"))
                    except OSError:
                        break
            finally:
                stop.set()

        read_task = asyncio.create_task(reader())
        write_task = asyncio.create_task(writer())
        try:
            await asyncio.wait({read_task, write_task}, return_when=asyncio.FIRST_COMPLETED)
        finally:
            stop.set()
            read_task.cancel()
            write_task.cancel()
            await asyncio.gather(read_task, write_task, return_exceptions=True)

    def _handle_control_frame(self, payload: str, master_fd: int) -> None:
        """Apply a client control frame — currently only terminal resize."""
        if len(payload) > _MAX_CONTROL_BYTES:
            return
        try:
            message = json.loads(payload)
            rows, cols = int(message["rows"]), int(message["cols"])
        except (ValueError, TypeError, KeyError):
            return
        if 0 < rows <= 1000 and 0 < cols <= 1000:
            self._set_winsize(master_fd, rows, cols)

    async def _teardown(
        self, websocket: WebSocket, child_pid: int, master_fd: int, slave_fd: int
    ) -> None:
        """Reap the shell, close the PTY, and close the socket."""
        if child_pid > 0:
            await self._reap_child(child_pid)

        for fd in (slave_fd, master_fd):
            if fd != -1:
                try:
                    os.close(fd)
                except OSError:
                    pass

        try:
            await websocket.close()
        except Exception:
            pass

    @staticmethod
    async def _reap_child(pid: int) -> None:
        """SIGHUP the shell, wait for it, then SIGKILL if it will not go."""
        try:
            os.kill(pid, signal.SIGHUP)
        except OSError:
            return  # already gone

        loop = asyncio.get_running_loop()
        for _ in range(_REAP_ATTEMPTS):
            try:
                # WNOHANG makes this a poll, not a blocking wait.
                if os.waitpid(pid, os.WNOHANG)[0] != 0:  # noqa: ASYNC222
                    return
            except ChildProcessError:
                return
            await asyncio.sleep(_REAP_INTERVAL)

        try:
            os.kill(pid, signal.SIGKILL)
            await loop.run_in_executor(None, os.waitpid, pid, 0)
        except (OSError, ChildProcessError):
            pass


#: The process-wide terminal manager.
terminal_manager = TerminalManager()
